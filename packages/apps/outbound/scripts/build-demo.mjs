// Build a SINGLE-FILE design demo of the outbox inbox for an Ikenga viewer pane.
//
// The viewer serves a previewed HTML file on its own (single-file / own-dir
// mount, opaque sandboxed origin, CSP: scripts only from 'self' + a few CDNs,
// images only 'self' / data: / blob:). So the demo must carry everything:
// the real dist build bundled inline (esm.sh deps stay external — allowed and
// CORS-enabled) and the fixture images inlined as data: URIs.
//
//   node scripts/build-demo.mjs [outFile]   (default: ../../../../design/outbox-redesign/inbox-demo.html)
import { execFileSync } from 'node:child_process';
import { readFileSync, writeFileSync, readdirSync, mkdtempSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const pkg = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const out = resolve(process.argv[2] ?? join(pkg, '../../../../design/outbox-redesign/inbox-demo.html'));
const tmp = mkdtempSync(join(tmpdir(), 'outbox-demo-'));
const entry = join(tmp, 'entry.js');
writeFileSync(entry, `import ${JSON.stringify(join(pkg, 'dist/app.js'))};\n`);
execFileSync('npx', ['-y', 'esbuild@0.24.2', entry, '--bundle', '--format=esm', '--external:https://*', '--minify', `--outfile=${join(tmp, 'b.js')}`], { stdio: 'inherit' });
const js = readFileSync(join(tmp, 'b.js'), 'utf8').replace(/<\/script/gi, '<\\/script');

const imgDir = join(pkg, 'demo/img');
const imgs = Object.fromEntries(readdirSync(imgDir).filter((f) => f.endsWith('.jpg'))
  .map((f) => [f.replace(/\.jpg$/, ''), `data:image/jpeg;base64,${readFileSync(join(imgDir, f)).toString('base64')}`]));

writeFileSync(out, `<!doctype html>
<html lang="en">
<head>
<meta charset="UTF-8" />
<meta name="viewport" content="width=device-width, initial-scale=1.0" />
<meta name="color-scheme" content="light dark" />
<title>Outbox · unified inbox (demo)</title>
<!-- GENERATED by ikenga-pkgs/packages/apps/outbound/scripts/build-demo.mjs — do not edit.
     The real com.ikenga.outbound build on demo rows, self-contained for an
     Ikenga viewer pane (or any browser). Nothing is saved. -->
<style>html,body,#root{height:100%;overflow:hidden;margin:0}#root>.boot{padding:1rem 1.25rem;font:13px system-ui;opacity:.7}</style>
</head>
<body>
<div id="root"><div class="boot">Loading outbox demo…</div></div>
<script>
try { window.parent = window; } catch (e) {}
window.__OUTBOX_DEMO_IMAGES = ${JSON.stringify(imgs)};
window.__OUTBOX_DEMO_IMG = (id) => window.__OUTBOX_DEMO_IMAGES[id];
window.addEventListener('error', (e) => { const r = document.querySelector('#root > .boot'); if (r) r.textContent = 'Failed to load: ' + (e.message || e); });
window.addEventListener('unhandledrejection', (e) => { const r = document.querySelector('#root > .boot'); if (r) r.textContent = 'Failed to load: ' + (e.reason?.message || e.reason); });
</script>
<script type="module">
${js}
</script>
</body>
</html>
`);
console.log(`[outbound demo] wrote ${out} (${Math.round(readFileSync(out).length / 1024)} KB)`);
