/** Write the project and its files to a fresh temp folder. */
export async function rulesFolder(mutate: (p: AkukoProject) => void = () => {}): Promise<{ dir: string; project: AkukoProject }> {
  const dir = await mkdtemp(join(tmpdir(), 'akuko-rules-'));
  for (const f of Object.values(FILES)) {
    await mkdir(dirname(join(dir, f.path)), { recursive: true });
    await writeFile(join(dir, f.path), f.data);
  }
  const project = rulesProject();
  mutate(project);
  await writeFile(join(dir, 'akuko.json'), serializeProject(AkukoProjectSchema.parse(project)));
  return { dir, project: AkukoProjectSchema.parse(project) };
}

/** A one-item job. */
export function job(item: Partial<JobItem> & Pick<JobItem, 'unit'>, o: Partial<Pick<Job, 'provider' | 'kind' | 'stage' | 'id'>> = {}): Job {
  return {
    id: o.id ?? 'job_test_1',
    stage: o.stage ?? 'keyframes',
    kind: o.kind ?? 'image',
    provider: o.provider ?? 'fal',
    label: 'test job',
    items: [{ prompt: '', output: 'keyframe', ...item }],
  };
}
