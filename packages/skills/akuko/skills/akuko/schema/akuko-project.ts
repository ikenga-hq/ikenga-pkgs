/**
 * akuko — project format v1 (`akuko.json`).
 *
 * One document describes a whole akuko project: the film's identity, the nine
 * pipeline stages, the script beats and scenes, every shot, the bibles
 * (characters, locations, styles), the asset register, audio, money (budget,
 * pending spend, ledger) and the decisions people made in a review surface.
 *
 * Built on `@ikenga/studio-schema`: enums and sub-shapes that mean the same
 * thing in both formats (aspect ratio, shot type, camera move, asset
 * references, script beats, narration, audio analysis) are composed from the
 * Studio Zod objects rather than copied, so the two formats cannot drift apart
 * silently. `convert/studio.ts` maps a Studio `storyboard.json` to and from
 * this format; `convert/freeform.ts` imports the older freeform storyboard.
 *
 * Design rules
 *   - akuko-owned objects are `.strict()`: unknown keys are an error, never
 *     silently kept. Fields that only exist so another format can round-trip
 *     live in explicit, typed slots (`studio`, `freeform`), never in a
 *     catch-all at the top level.
 *   - `format` + `schema_version` are literals so future migrations can tell
 *     versions apart.
 *   - The Zod schema is structural and is exported 1:1 as JSON Schema
 *     (`akuko-project.schema.json`, generated by `export-json-schema.ts`).
 *     Cross-references (shot → scene, refs → bible/asset, ledger → unit,
 *     budget.spent vs ledger) are checked by `integrity.ts`, because JSON
 *     Schema cannot express them.
 *   - Status changes to `approved` are made by people only. Actions move a
 *     unit to `pending-review`; a review surface records a `Decision`; the
 *     next action folds decisions into `status`, `comments` and
 *     `pending_spend`.
 */

